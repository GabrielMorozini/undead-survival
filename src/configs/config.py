def gerenciar_eventos_menu(evento, indice_selecionado, opcoes_menu):
    import pygame
    if evento.key == pygame.K_UP:
        indice_selecionado = (indice_selecionado - 1) % len(opcoes_menu)
    elif evento.key == pygame.K_DOWN:
        indice_selecionado = (indice_selecionado + 1) % len(opcoes_menu)
    return indice_selecionado